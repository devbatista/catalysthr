require "rails_helper"

# D-614 (AGENTS.md, section 3): every table has a UUIDv7 primary key and every column that
# points to a row is a UUID. The only exception is solid_cache_entries, whose gem
# estimates the cache size from max(id) - min(id).
RSpec.describe "UUID primary keys" do
  let(:connection) { ActiveRecord::Base.connection }
  let(:numeric_tables) { %w[solid_cache_entries schema_migrations ar_internal_metadata] }
  let(:tables) { connection.tables - numeric_tables }

  it "gives every table a UUID primary key generated by uuidv7()" do
    wrong = tables.reject do |table|
      column = connection.columns(table).find { |candidate| candidate.name == connection.primary_key(table) }
      column&.sql_type == "uuid" && column.default_function == "uuidv7()"
    end

    expect(wrong).to be_empty
  end

  # A reference is a foreign key, the id of a polymorphic pair, or any *_id column with a
  # number in it. Identifiers of other systems (request_id, provider_message_id) are text.
  it "makes every reference a UUID" do
    wrong = tables.flat_map do |table|
      columns = connection.columns(table)
      foreign = connection.foreign_keys(table).map(&:column)
      polymorphic = columns.map(&:name).grep(/_type\z/).map { |name| name.sub(/_type\z/, "_id") }
      columns.select do |column|
        reference = column.name.in?(foreign) || column.name.in?(polymorphic)
        numeric_id = column.name.end_with?("_id", "_ids") && column.type.in?(%i[integer bigint])
        (reference || numeric_id) && !column.sql_type.start_with?("uuid")
      end.map { |column| "#{table}.#{column.name} (#{column.sql_type})" }
    end

    expect(wrong).to be_empty
  end

  it "refuses a migration that creates a table without the UUIDv7 key" do
    migration = Class.new(ActiveRecord::Migration[8.1]) do
      def change
        create_table :probes
      end
    end
    stub_const("StrongMigrations::Checker", StrongMigrations::Checker)

    expect {
      ActiveRecord::Migration.suppress_messages do
        ActiveRecord::Base.transaction(requires_new: true) do
          migration.new.tap { |instance| instance.version = 99_991_231_000_000 }.migrate(:up)
          raise ActiveRecord::Rollback
        end
      end
    }.to raise_error(StrongMigrations::Error, /UUIDv7 primary key \(D-614\)/)
  end
end
