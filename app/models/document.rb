# A document of a person's folder, of one type (spec 08, D-270): each upload is a version,
# and the newest approved one is the one in force (RN-08-023). The HR sends a new document
# from the folder, or a new version of this one; a dependent's certificate and a bank
# account's proof point to them (D-604). What the modules generate is read only here
# (RN-08-070).
class Document < ApplicationRecord
  STATUSES = %w[pending valid expiring expired].freeze
  SOURCES = %w[employee hr process batch generated].freeze

  acts_as_tenant :company

  audited

  belongs_to :worker_profile
  belongs_to :document_type
  belongs_to :current_version, class_name: "DocumentVersion", optional: true
  belongs_to :source_ref, polymorphic: true, optional: true
  belongs_to :dependent, optional: true
  belongs_to :bank_account, optional: true
  belongs_to :deleted_by, class_name: "User", optional: true
  has_many :versions, -> { order(:number) }, class_name: "DocumentVersion", inverse_of: :document, dependent: nil

  # Prefixed: "valid" would clash with valid?.
  enum :status, STATUSES.index_by(&:itself), validate: true, prefix: true
  enum :source, SOURCES.index_by(&:itself), validate: true, prefix: :from

  validate :same_person

  scope :kept, -> { where(deleted_at: nil) }
  # What the employee sees in their own folder: no internal type (D-274, CA-08-008).
  scope :for_employee, -> { kept.joins(:document_type).where(document_types: { internal: false }) }

  def audit_company_id
    company_id
  end

  delegate :category, :sensitive?, to: :document_type

  def latest_version
    versions.max_by(&:number)
  end

  # Generated by a module, so never replaced from the folder (RN-08-070, P-08-18).
  def read_only?
    from_generated?
  end

  # The process item this document answers, when it came from one (D-642).
  def process_item
    source_ref if source_ref_type == "ProcessItem"
  end

  private

  def same_person
    errors.add(:dependent, :invalid) if dependent && dependent.worker_profile_id != worker_profile_id
    errors.add(:bank_account, :invalid) if bank_account && bank_account.worker_profile_id != worker_profile_id
  end
end
